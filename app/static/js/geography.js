function points(geo) {
  return geo.map(([lat, lon]) => project(lat, lon).join(",")).join(" ");
}

export function drawGeography(layer, labels) {
  layer.append(svg("rect", { x: -1500, y: -1500, width: 5000, height: 5000, fill: "var(--map)" }));
  layer.append(svg("polygon", { points: points(boundary), class: "geo-land" }));
  [[boundary.slice(0, 7), [[28.678,77.245],[28.656,77.192],[28.67,77.136],[28.69,77.07]]],
    [boundary.slice(11, 20), [[28.541,77.152],[28.583,77.177],[28.595,77.245]]]].forEach(
    (parts) => layer.append(svg("polygon", { points: points(parts.flat()), class: "geo-district" })),
  );
  for (const park of parks) layer.append(svg("polygon", { points: points(park), class: "geo-park" }));
  for (const road of minor) layer.append(svg("polyline", { points: points(road), class: "geo-road" }));
  layer.append(svg("polyline", { points: points(river), class: "geo-river-bank" }),
    svg("polyline", { points: points(river), class: "geo-river" }));
  for (const road of major) layer.append(svg("polyline", { points: points(road), class: "geo-road major" }));
  for (const [label, lat, lon, cls] of [
    ["NORTH DELHI",28.745,77.12],["WEST DELHI",28.671,77.034],["CENTRAL DELHI",28.614,77.169],
    ["SOUTH DELHI",28.515,77.222],["EAST DELHI",28.704,77.305],["NOIDA",28.549,77.355],
    ["GURUGRAM",28.452,77.043],["FARIDABAD",28.390,77.326],["GREATER NOIDA",28.447,77.473],["Yamuna",28.629,77.255,"geo-river-label"],
  ]) {
    const [x, y] = project(lat, lon);
    const text = svg("text", { x, y, class: cls || "geo-label" });
    text.textContent = label;
    labels.append(text);
  }
}
